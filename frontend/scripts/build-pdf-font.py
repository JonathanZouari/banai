"""One-off build step: Heebo (SIL OFL, @fontsource/heebo) -> TTF for jsPDF -> base64 JS module.

jsPDF embeds TrueType fonts, while @fontsource ships woff split into hebrew and latin subsets.
This merges both subsets per weight into one TTF and writes src/pdf/fonts/heebo.js.
Run from frontend/:  python3 scripts/build-pdf-font.py   (needs fonttools)
"""
import base64
import io
from pathlib import Path

from fontTools.merge import Merger
from fontTools.ttLib import TTFont

FILES = Path("node_modules/@fontsource/heebo/files")
OUT = Path("src/pdf/fonts/heebo.js")


def merged_ttf(weight: int) -> bytes:
    fonts = []
    for subset in ("latin", "hebrew"):
        font = TTFont(FILES / f"heebo-{subset}-{weight}-normal.woff")
        font.flavor = None  # plain TrueType
        buffer = io.BytesIO()
        font.save(buffer)
        buffer.seek(0)
        fonts.append(buffer)
    paths = []
    for index, buffer in enumerate(fonts):
        path = Path(f"/tmp/heebo-{weight}-{index}.ttf")
        path.write_bytes(buffer.read())
        paths.append(str(path))
    merged = Merger().merge(paths)
    out = io.BytesIO()
    merged.save(out)
    return out.getvalue()


def main() -> None:
    parts = {name: base64.b64encode(merged_ttf(weight)).decode() for name, weight in (("regular", 400), ("bold", 700))}
    OUT.write_text(
        "// GENERATED by scripts/build-pdf-font.py from @fontsource/heebo (SIL Open Font License 1.1). Do not edit.\n"
        + "".join(f"export const HEEBO_{name.upper()} = '{data}';\n" for name, data in parts.items()),
        encoding="utf-8",
    )
    print({name: len(data) for name, data in parts.items()})


main()
